"""
router_ctl.py — thin wrapper around router.sh (iptables / PF / firewall).

Author : Kage
Project: krouter
Thought: Python decides policy; shell owns the messy iptables. SAFE/DRY keeps
         the family internet up while I test.
"""
from __future__ import annotations

import logging
import os
import subprocess
from typing import Optional

import config
import policy
import settings_store

log = logging.getLogger('router_ctl')


def _script() -> str:
    return getattr(config, 'ROUTER_SCRIPT', './router.sh')


def _dry() -> bool:
    return bool(getattr(config, 'ROUTER_DRY_RUN', True) or getattr(config, 'SAFE_MODE', True))


def _env() -> dict:
    env = os.environ.copy()
    env.update(settings_store.router_env())
    return env


def _run_router(args: list[str]) -> tuple[bool, str]:
    """
    Run router.sh with Settings NIC env.
    Do NOT use `sudo -E` — on this host (sudo-rs) -E is ignored, so INB/OUT
    never reach the script and every set/refresh fails with "INB/OUT unset".
    Root: run directly with env=. Non-root: `sudo env INB=... OUT=... bash script`.
    """
    env = _env()
    script = os.path.abspath(_script())
    inb, out_if = env.get('INB', ''), env.get('OUT', '')
    if _dry():
        note = f'DRY_RUN: would run: INB={inb} OUT={out_if} {script} {" ".join(args)}'
        log.info(note)
        return True, note
    if not inb or not out_if:
        msg = 'INB/OUT unset in settings — configure Internal/WAN device in Settings'
        log.error(msg)
        return False, msg
    try:
        if os.geteuid() == 0:
            cmd = ['bash', script, *args]
            rt = subprocess.run(cmd, capture_output=True, text=True, env=env)
        else:
            cmd = [
                'sudo', 'env',
                f'INB={inb}',
                f'OUT={out_if}',
                f'SERVER_IP_DEFAULT={env.get("SERVER_IP_DEFAULT", "")}',
                f'ROUTER_DNS_IP={env.get("ROUTER_DNS_IP", "")}',
                f'KROUTER_DRY_RUN={env.get("KROUTER_DRY_RUN", os.environ.get("KROUTER_DRY_RUN", "0"))}',
                'bash', script, *args,
            ]
            rt = subprocess.run(cmd, capture_output=True, text=True)
        out = (rt.stdout or '') + (rt.stderr or '')
        ok = rt.returncode == 0
        if ok:
            log.info(f'router {" ".join(args)}: {out.strip()}')
        else:
            log.error(f'router {" ".join(args)} failed: {out.strip()}')
        return ok, out
    except Exception as e:
        log.error(f'router {" ".join(args)} exception: {e}')
        return False, str(e)


def apply_chain(mac: str, chain: str) -> tuple[bool, str]:
    """
    chain: DEFAULT | ALL_ALLOW | STUDY | BLOCK
    """
    mac = mac.strip().lower()
    chain = chain.upper()
    if chain not in policy.CHAINS:
        return False, f'invalid chain {chain}'
    return _run_router(['set', mac, chain])


def apply_effective(mac: str, mode: str, allow_until: Optional[int] = None,
                    study_until: Optional[int] = None, **kw) -> tuple[str, bool, str]:
    eff = policy.effective_mode(
        mode, allow_until, study_until=study_until, **kw)
    ok, msg = apply_chain(mac, eff)
    return eff, ok, msg


def refresh_block() -> tuple[bool, str]:
    """BLOCK 체인 재구성 (data/block_allow.conf 반영)."""
    return _run_router(['refresh-block'])


def router_init() -> tuple[bool, str]:
    """iptables base + chains (Settings NIC 반영)."""
    return _run_router(['init'])


def write_block_allow_conf(rules: list) -> str:
    """rules: ['tcp:1.2.3.4:443', ...] → data/block_allow.conf 기록. 경로 반환."""
    path = os.path.join(config.KROUTER_ROOT, 'data', 'block_allow.conf')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = [
        '# BLOCK allow — one rule per line: proto:ip:port',
        '# proto=tcp|udp|any  port=number|*',
    ]
    for r in rules or []:
        r = str(r).strip()
        if r and not r.startswith('#'):
            lines.append(r)
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return path


def write_firewall_conf(enabled: bool, forwards: list) -> tuple[str, str]:
    """settings → data/firewall.conf + data/port_forward.conf."""
    data = os.path.join(config.KROUTER_ROOT, 'data')
    os.makedirs(data, exist_ok=True)
    fw_path = os.path.join(data, 'firewall.conf')
    pf_path = os.path.join(data, 'port_forward.conf')
    with open(fw_path, 'w') as f:
        f.write(f"# generated by admin — do not edit by hand\nENABLED={'1' if enabled else '0'}\n")
    lines = [
        '# proto wan_port dest_ip dest_port',
        '# 라우터 자체 웹서버면 dest_ip = gateway (예 192.168.0.1)',
    ]
    for r in forwards or []:
        if not r.get('enabled', True):
            continue
        proto = str(r.get('proto', 'tcp')).lower().strip()
        try:
            wan_port = int(r.get('wan_port'))
            dest_port = int(r.get('dest_port'))
        except (TypeError, ValueError):
            continue
        dest_ip = str(r.get('dest_ip', '')).strip()
        if proto not in ('tcp', 'udp') or not dest_ip:
            continue
        if not (1 <= wan_port <= 65535 and 1 <= dest_port <= 65535):
            continue
        lines.append(f'{proto} {wan_port} {dest_ip} {dest_port}')
    with open(pf_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return fw_path, pf_path


def refresh_pf() -> tuple[bool, str]:
    """Firewall / port-forward 체인 재적용."""
    return _run_router(['refresh-pf'])


def apply_firewall_settings() -> tuple[bool, str]:
    """settings.db → conf 파일 → refresh-pf."""
    s = settings_store.get_all()
    write_firewall_conf(bool(s.get('firewall_enabled')), s.get('port_forwards') or [])
    return refresh_pf()


def apply_arp_table_size(size: int | None = None) -> tuple[bool, str]:
    """
    Apply ARP/neighbor knobs from Settings preset via sysctl -w only.
    Does not write /etc/sysctl.d (host-owned conf files left alone).
    Preset includes gc_thresh1/2/3, gc_stale_time, base_reachable_time_ms,
    mcast_solicit, ucast_solicit — no IPv6 toggles.
    """
    if size is None:
        try:
            size = int(settings_store.get('arp_table_size') or 100)
        except (TypeError, ValueError):
            size = 100
    try:
        size = int(size)
    except (TypeError, ValueError):
        return False, 'invalid arp_table_size'
    if size not in settings_store.ARP_TABLE_CHOICES:
        return False, f'arp_table_size not in allowed set: {size}'
    preset = settings_store.arp_preset(size)
    pairs = [
        ('net.ipv4.neigh.default.gc_thresh1', preset['gc_thresh1']),
        ('net.ipv4.neigh.default.gc_thresh2', preset['gc_thresh2']),
        ('net.ipv4.neigh.default.gc_thresh3', preset['gc_thresh3']),
        ('net.ipv4.neigh.default.gc_stale_time', preset['gc_stale_time']),
        ('net.ipv4.neigh.default.base_reachable_time_ms', preset['base_reachable_time_ms']),
        ('net.ipv4.neigh.default.mcast_solicit', preset['mcast_solicit']),
        ('net.ipv4.neigh.default.ucast_solicit', preset['ucast_solicit']),
    ]
    summary = (
        f"size={size} thresh={preset['gc_thresh1']}/{preset['gc_thresh2']}/{preset['gc_thresh3']} "
        f"stale={preset['gc_stale_time']} reachable_ms={preset['base_reachable_time_ms']} "
        f"solicit={preset['mcast_solicit']}/{preset['ucast_solicit']}"
    )
    if _dry():
        note = f'DRY_RUN: would sysctl -w ARP {summary}'
        log.info(note)
        return True, note
    prefix = [] if os.geteuid() == 0 else ['sudo']
    errors = []
    applied = []
    try:
        for key, val in pairs:
            rt = subprocess.run(
                prefix + ['sysctl', '-w', f'{key}={val}'],
                capture_output=True, text=True)
            out = ((rt.stdout or '') + (rt.stderr or '')).strip()
            if rt.returncode != 0:
                errors.append(out or f'{key} failed')
            else:
                applied.append(f'{key}={val}')
        ok = not errors
        msg = summary + ((' | ' + '; '.join(errors)) if errors else '')
        if ok:
            log.info(f'ARP applied: {summary}')
        else:
            log.error(f'ARP apply partial/fail: {msg}')
        return ok, msg
    except Exception as e:
        log.error(f'ARP apply exception: {e}')
        return False, str(e)


def schedule_stack_restart(delay_sec: float = 1.0) -> None:
    """UI 에서 호출: 잠시 후 krouterctl restart (자기 프로세스 포함 재기동)."""
    ctl = os.path.join(config.KROUTER_ROOT, 'krouterctl')
    # 새 세션으로 떼어내어 admin 이 죽어도 restart 완료
    subprocess.Popen(
        ['bash', '-c', f'sleep {delay_sec}; exec "{ctl}" restart'],
        cwd=config.KROUTER_ROOT,
        start_new_session=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
