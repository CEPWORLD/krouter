"""
router_ctl.py — thin wrapper around router.sh (iptables / PF / firewall).

Author : Kage
Project: krouter
Thought: Python decides policy; shell owns the messy iptables. SAFE/DRY keeps
         the family internet up while I test.
"""
from __future__ import annotations

import logging
import os
import subprocess
from typing import Optional

import config
import policy
import settings_store

log = logging.getLogger('router_ctl')


def _script() -> str:
    return getattr(config, 'ROUTER_SCRIPT', './router.sh')


def _dry() -> bool:
    return bool(getattr(config, 'ROUTER_DRY_RUN', True) or getattr(config, 'SAFE_MODE', True))


def _env() -> dict:
    env = os.environ.copy()
    env.update(settings_store.router_env())
    return env


def _run_router(args: list[str]) -> tuple[bool, str]:
    cmd = ['sudo', '-E', _script(), *args]
    if _dry():
        note = f'DRY_RUN: would run: INB={_env().get("INB")} OUT={_env().get("OUT")} {" ".join(cmd)}'
        log.info(note)
        return True, note
    try:
        rt = subprocess.run(cmd, capture_output=True, text=True, env=_env())
        out = (rt.stdout or '') + (rt.stderr or '')
        ok = rt.returncode == 0
        if ok:
            log.info(f'router {" ".join(args)}: {out.strip()}')
        else:
            log.error(f'router {" ".join(args)} failed: {out.strip()}')
        return ok, out
    except Exception as e:
        log.error(f'router {" ".join(args)} exception: {e}')
        return False, str(e)


def apply_chain(mac: str, chain: str) -> tuple[bool, str]:
    """
    chain: DEFAULT | ALL_ALLOW | STUDY | BLOCK
    """
    mac = mac.strip().lower()
    chain = chain.upper()
    if chain not in policy.CHAINS:
        return False, f'invalid chain {chain}'
    return _run_router(['set', mac, chain])


def apply_effective(mac: str, mode: str, allow_until: Optional[int] = None,
                    study_start: str = '06:00', study_end: str = '22:00') -> tuple[str, bool, str]:
    eff = policy.effective_mode(mode, allow_until, study_start=study_start, study_end=study_end)
    ok, msg = apply_chain(mac, eff)
    return eff, ok, msg


def refresh_block() -> tuple[bool, str]:
    """BLOCK 체인 재구성 (data/block_allow.conf 반영)."""
    return _run_router(['refresh-block'])


def router_init() -> tuple[bool, str]:
    """iptables base + chains (Settings NIC 반영)."""
    return _run_router(['init'])


def write_block_allow_conf(rules: list) -> str:
    """rules: ['tcp:1.2.3.4:443', ...] → data/block_allow.conf 기록. 경로 반환."""
    path = os.path.join(config.KROUTER_ROOT, 'data', 'block_allow.conf')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = [
        '# BLOCK allow — one rule per line: proto:ip:port',
        '# proto=tcp|udp|any  port=number|*',
    ]
    for r in rules or []:
        r = str(r).strip()
        if r and not r.startswith('#'):
            lines.append(r)
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return path


def write_firewall_conf(enabled: bool, forwards: list) -> tuple[str, str]:
    """settings → data/firewall.conf + data/port_forward.conf."""
    data = os.path.join(config.KROUTER_ROOT, 'data')
    os.makedirs(data, exist_ok=True)
    fw_path = os.path.join(data, 'firewall.conf')
    pf_path = os.path.join(data, 'port_forward.conf')
    with open(fw_path, 'w') as f:
        f.write(f"# generated by admin — do not edit by hand\nENABLED={'1' if enabled else '0'}\n")
    lines = [
        '# proto wan_port dest_ip dest_port',
        '# 라우터 자체 웹서버면 dest_ip = gateway (예 192.168.0.1)',
    ]
    for r in forwards or []:
        if not r.get('enabled', True):
            continue
        proto = str(r.get('proto', 'tcp')).lower().strip()
        try:
            wan_port = int(r.get('wan_port'))
            dest_port = int(r.get('dest_port'))
        except (TypeError, ValueError):
            continue
        dest_ip = str(r.get('dest_ip', '')).strip()
        if proto not in ('tcp', 'udp') or not dest_ip:
            continue
        if not (1 <= wan_port <= 65535 and 1 <= dest_port <= 65535):
            continue
        lines.append(f'{proto} {wan_port} {dest_ip} {dest_port}')
    with open(pf_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return fw_path, pf_path


def refresh_pf() -> tuple[bool, str]:
    """Firewall / port-forward 체인 재적용."""
    return _run_router(['refresh-pf'])


def apply_firewall_settings() -> tuple[bool, str]:
    """settings.db → conf 파일 → refresh-pf."""
    s = settings_store.get_all()
    write_firewall_conf(bool(s.get('firewall_enabled')), s.get('port_forwards') or [])
    return refresh_pf()


def apply_arp_table_size(size: int | None = None) -> tuple[bool, str]:
    """
    Apply ARP/neighbor GC thresholds from Settings.
    size = gc_thresh1; thresh2=size*4, thresh3=size*8 (same ratio as common home tuning).
    Writes /etc/sysctl.d/98-krouter-arp.conf and runs sysctl -p (unless DRY/SAFE).
    """
    if size is None:
        size = int(settings_store.get('arp_table_size') or 100)
    try:
        size = int(size)
    except (TypeError, ValueError):
        return False, 'invalid arp_table_size'
    if size not in getattr(settings_store, 'ARP_TABLE_CHOICES', (100, 200, 512, 1024, 2048)):
        return False, f'arp_table_size not in allowed set: {size}'
    t1, t2, t3 = size, size * 4, size * 8
    conf = (
        f'# generated by krouter — ARP / neighbor table sizing\n'
        f'# Selected size={size} → gc_thresh1/2/3\n'
        f'net.ipv4.neigh.default.gc_thresh1 = {t1}\n'
        f'net.ipv4.neigh.default.gc_thresh2 = {t2}\n'
        f'net.ipv4.neigh.default.gc_thresh3 = {t3}\n'
    )
    path = '/etc/sysctl.d/98-krouter-arp.conf'
    staging = os.path.join(config.KROUTER_ROOT, 'data', '98-krouter-arp.conf')
    os.makedirs(os.path.dirname(staging), exist_ok=True)
    with open(staging, 'w') as f:
        f.write(conf)
    if _dry():
        note = f'DRY_RUN: would apply ARP size={size} ({t1}/{t2}/{t3}) via {path}'
        log.info(note)
        return True, note
    try:
        subprocess.run(['sudo', 'cp', staging, path], check=True, capture_output=True, text=True)
        rt = subprocess.run(
            ['sudo', 'sysctl', '-w',
             f'net.ipv4.neigh.default.gc_thresh1={t1}',
             f'net.ipv4.neigh.default.gc_thresh2={t2}',
             f'net.ipv4.neigh.default.gc_thresh3={t3}'],
            capture_output=True, text=True)
        out = (rt.stdout or '') + (rt.stderr or '')
        ok = rt.returncode == 0
        if ok:
            log.info(f'ARP table size={size} applied ({t1}/{t2}/{t3})')
        else:
            log.error(f'ARP sysctl failed: {out.strip()}')
        return ok, out or f'applied size={size}'
    except Exception as e:
        log.error(f'ARP apply exception: {e}')
        return False, str(e)


def schedule_stack_restart(delay_sec: float = 1.0) -> None:
    """UI 에서 호출: 잠시 후 krouterctl restart (자기 프로세스 포함 재기동)."""
    ctl = os.path.join(config.KROUTER_ROOT, 'krouterctl')
    # 새 세션으로 떼어내어 admin 이 죽어도 restart 완료
    subprocess.Popen(
        ['bash', '-c', f'sleep {delay_sec}; exec "{ctl}" restart'],
        cwd=config.KROUTER_ROOT,
        start_new_session=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
